param(
    # 默认取本机标准安装位置；可用 -SdkRoot / -NdkRoot / -JdkRoot 覆盖。
    [string]$SdkRoot = "$env:LOCALAPPDATA\Android\Sdk",
    [string]$JdkRoot = "$env:ProgramFiles\Eclipse Adoptium\jdk-17.0.20.8-hotspot",
    [string]$NdkRoot = "$env:LOCALAPPDATA\Android\Sdk\ndk\27.0.12077973",
    [string]$BuildDirectory = "$env:TEMP\aurora-build\capture-helper"
)
$ErrorActionPreference = "Stop"
$captureSource = Join-Path $PSScriptRoot "java\com\aurora\capture\CaptureHelper.java"
$captureMirrorSource = Join-Path $PSScriptRoot "java\com\aurora\capture\MirrorCapture.java"
$captureTestDisplaySource = Join-Path $PSScriptRoot "java\com\aurora\capture\TestDisplay.java"
$captureJar = Join-Path $SdkRoot "platforms\android-36\android.jar"
$captureJavac = Join-Path $JdkRoot "bin\javac.exe"
$captureD8 = Join-Path $SdkRoot "build-tools\36.0.0\d8.bat"
foreach ($captureTool in @($captureSource, $captureMirrorSource, $captureTestDisplaySource, $captureJar, $captureJavac, $captureD8)) {
    if (-not (Test-Path -LiteralPath $captureTool)) { throw "Missing: $captureTool" }
}
$captureClasses = Join-Path $BuildDirectory "classes"
$captureDex = Join-Path $BuildDirectory "dex"
New-Item -ItemType Directory -Force -Path $captureClasses, $captureDex | Out-Null
& $captureJavac -source 8 -target 8 -encoding UTF-8 -classpath $captureJar -d $captureClasses $captureSource $captureMirrorSource $captureTestDisplaySource
if ($LASTEXITCODE -ne 0) { throw "javac failed" }
$captureClassFiles = @(Get-ChildItem -LiteralPath $captureClasses -Recurse -Filter *.class | ForEach-Object { $_.FullName })
& $captureD8 --release --min-api 29 --lib $captureJar --output $captureDex $captureClassFiles
if ($LASTEXITCODE -ne 0) { throw "d8 failed" }
$captureBytes = [IO.File]::ReadAllBytes((Join-Path $captureDex "classes.dex"))
$captureStandaloneDex = Join-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) "..\build\realtime-capture\classes.dex"
New-Item -ItemType Directory -Force -Path (Split-Path $captureStandaloneDex -Parent) | Out-Null
[IO.File]::WriteAllBytes($captureStandaloneDex, $captureBytes)
$captureHeader = [Text.StringBuilder]::new()
[void]$captureHeader.AppendLine("// Generated by realtime_capture/build-helper.ps1. Embedded framework capture dex.")
[void]$captureHeader.AppendLine("#pragma once")
[void]$captureHeader.AppendLine("static const unsigned char kAuroraCaptureDex[] = {")
for ($captureIndex = 0; $captureIndex -lt $captureBytes.Length; $captureIndex++) {
    if ($captureIndex % 16 -eq 0) { [void]$captureHeader.Append("`n    ") }
    [void]$captureHeader.AppendFormat("0x{0:x2},", $captureBytes[$captureIndex])
}
[void]$captureHeader.AppendLine("`n};")
[void]$captureHeader.AppendLine("static const unsigned int kAuroraCaptureDexSize = $($captureBytes.Length)u;")
$captureOutputHeader = Join-Path (Split-Path $PSScriptRoot -Parent) "AuroraCaptureDex.h"
[IO.File]::WriteAllText($captureOutputHeader, $captureHeader.ToString(), [Text.UTF8Encoding]::new($false))
Write-Host "Capture dex: $($captureBytes.Length) bytes; embedded header: $captureOutputHeader"

$captureClang = Join-Path $NdkRoot "toolchains\llvm\prebuilt\windows-x86_64\bin\clang++.exe"
$captureNativePath = Join-Path $BuildDirectory "libaurora_capture_send.so"
& $captureClang --target=aarch64-linux-android29 -std=c++17 -fPIC -shared -O2 -fno-exceptions -fno-rtti -nostdlib++ `
    '-Wl,--strip-all' '-Wl,-soname,libaurora_capture_send.so' `
    (Join-Path $PSScriptRoot "HardwareBufferSend.cpp") -landroid -o $captureNativePath
if ($LASTEXITCODE -ne 0) { throw "Capture JNI build failed" }
$captureNativeBytes = [IO.File]::ReadAllBytes($captureNativePath)
$captureNativeHeader = [Text.StringBuilder]::new()
[void]$captureNativeHeader.AppendLine("// Generated by realtime_capture/build-helper.ps1. Embedded AHardwareBuffer sender.")
[void]$captureNativeHeader.AppendLine("#pragma once")
[void]$captureNativeHeader.AppendLine("static const unsigned char kAuroraCaptureNative[] = {")
for ($captureIndex = 0; $captureIndex -lt $captureNativeBytes.Length; $captureIndex++) {
    if ($captureIndex % 16 -eq 0) { [void]$captureNativeHeader.Append("`n    ") }
    [void]$captureNativeHeader.AppendFormat("0x{0:x2},", $captureNativeBytes[$captureIndex])
}
[void]$captureNativeHeader.AppendLine("`n};")
[void]$captureNativeHeader.AppendLine("static const unsigned int kAuroraCaptureNativeSize = $($captureNativeBytes.Length)u;")
$captureNativeOutputHeader = Join-Path (Split-Path $PSScriptRoot -Parent) "AuroraCaptureNative.h"
[IO.File]::WriteAllText($captureNativeOutputHeader, $captureNativeHeader.ToString(), [Text.UTF8Encoding]::new($false))
Write-Host "Capture JNI: $($captureNativeBytes.Length) bytes; embedded header: $captureNativeOutputHeader"
