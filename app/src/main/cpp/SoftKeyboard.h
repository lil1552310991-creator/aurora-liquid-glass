// -----------------------------------------------------------------------------
// 软键盘（SoftKeyboard）—— 纯 ImGui 自绘，零 Java / 零 APK
//
// 为什么要有它：
//   原来窗口里的「文本输入」靠拉起系统输入法。那条路必须有一个**已安装的 APK**
//   提供 WindowManager 窗口（输入焦点目标），因为 app_process 起的进程不在 AMS
//   的 mProcessMap 里，拿不到 WMS 窗口（见 ime-bridge/Main.java 的说明）。
//   用户明确要求：这个项目里不允许出现任何 APK。
//
//   于是改成自己画键盘。整条链路没有任何 Java 组件：
//     · 布局与绘制：ImGui（同一个 UI，同一套字体）
//     · 文本写入：把按键转换成 io.AddInputCharacter / AddKeyEvent，
//       ImGui 的 InputText 本来就处理光标、选区、退格、Ctrl+A 之类，
//       所以这里只要"敲键盘"，不需要自己维护编辑状态。
//
// 能力边界（如实说明）：
//   · 英文、数字、常用符号：完整支持。
//   · 中文：需要拼音/形码引擎与候选词库（几十万字的表 + 词频），本项目不内置。
//     这是"零 APK"的直接代价 —— 系统输入法自带这个引擎，自绘键盘没有。
//   · 剪贴板：仍可用 ImGui 的 Ctrl+V（Clipoard 回调由宿主注入）。
//
// 交互设计：
//   · 点击输入框自动弹出；点「收起」或点输入框以外的地方自动收起。
//   · 键盘画在**屏幕底部**，不跟随窗口 —— 窗口可能被拖到任何位置，
//     键盘固定在底部才符合肌肉记忆（和系统输入法一致）。
//   · 高度按屏幕尺寸自适应，保证在竖屏/横屏下都不遮住输入框太多。
// -----------------------------------------------------------------------------

namespace aurora::softkb {

// 键盘当前是否展开。
bool Visible();

// 由输入框在获得焦点时调用：请求展开键盘。
void RequestShow();

// 收起键盘。
void Hide();

// 每帧调用一次（在 ImGui 帧内、所有窗口绘制完成之后）。
// 内部绘制键盘并把按键送进 ImGui 的输入队列。
void Draw();

// ---- 键盘布局参数（供测试断言，纯逻辑）----

// 一行的键数上限（用于估算每条按键的宽度）。
int MaxKeysPerRow();

// 键盘总高度占屏幕高度的比例（会夹在 [kMinRatio, kMaxRatio] 内）。
float HeightRatioFor(int screenW, int screenH);

}  // namespace aurora::softkb
