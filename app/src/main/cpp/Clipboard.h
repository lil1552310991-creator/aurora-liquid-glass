// -----------------------------------------------------------------------------
// 剪贴板粘贴（Clipboard）—— 纯 native，零 Java / 零 APK
//
// 为什么是"粘贴"而不是"键盘"：
//   系统输入法必须有 WMS 窗口做焦点目标，而 WMS 窗口必须来自 AMS 注册的进程，
//   AMS 注册又必须有已安装的包。这条链在 Android 上是硬约束：不装 APK 就没有
//   窗口，没有窗口就拉不起输入法。自绘键盘能绕过它，但用户不接受。
//
//   于是用剪贴板：用户在**系统输入法**里打任意文字（中文、表情、什么都可以），
//   复制，回到这个窗口点"粘贴"。中文完全可行，因为它根本不经过我们的代码 ——
//   文字是系统输入法自己打出来的，我们只是把 ClipData 读出来。
//
// 实现方式：
//   1. 通过 servicemanager 拿 "clipboard" 服务的 binder（复用 aosp_glue 的
//      getServiceByHandle0，那是真机验证过的路径）；
//   2. **扫描 transaction code**：IClipboard 的方法每个 Android 版本都会重排，
//      写死 code 必然在某次系统更新后失效。这里逐个 code 试，看哪个返回的
//      parcel 里能解析出文本；
//   3. 解析 ClipData：不做完整的结构化反序列化（那个格式版本间变化很大），
//      而是按 "text/plain" 标记定位，取它后面的 String16。
//
// 能力边界（如实说明）：
//   · 只取文本。图片/URI/Intent 类型的剪贴板内容不处理（这个窗口也用不上）。
//   · 需要剪贴板里确实有文本；空剪贴板返回空串。
//   · 版本兼容靠"扫描 + 启发式"，没有写死任何 Android 版本号。
// -----------------------------------------------------------------------------

#include <string>

namespace aurora::clipboard {

// 读一次系统剪贴板里的文本。
//
// 成功返回 true 并把文本写进 out（UTF-8）。
// 失败/空剪贴板返回 false，并在 error 里给出原因（可为空）。
//
// 注意：这是个跨进程 binder 调用，通常在毫秒级，但**不要在每帧调用** ——
// UI 只在用户点"粘贴"时调一次。
bool ReadText(std::string* out, std::string* error);

}  // namespace aurora::clipboard
